// Pure rendering helpers for scripts/generate.ts, kept free of Bun APIs so Vitest can test them.

export type Icon = { name: string; outline: string; solid: string };

const HEADER = '// Generated by scripts/generate.ts from heroicons. Do not edit.';

export const componentName = (name: string) =>
	name
		.split('-')
		.map((part) => part.charAt(0).toUpperCase() + part.slice(1))
		.join('') + 'Icon';

/** Returns the markup inside the root <svg> element, without line breaks between children. */
export const svgBody = (svg: string) => {
	const match = svg.match(/<svg[^>]*>([\s\S]*)<\/svg>/);
	if (!match) throw new Error(`Not an SVG document: ${svg.slice(0, 50)}`);
	return match[1].replace(/\n\s*/g, '').trim();
};

export const renderComponent = ({ outline, solid }: Icon) => `<script lang="ts">
	import type { IconProps } from '../types.js';

	import IconBase from '../IconBase.svelte';

	const props: IconProps = $props();
</script>

<IconBase {...props} paths={{ outline: ${JSON.stringify(outline)}, solid: ${JSON.stringify(solid)} }} />
`;

export const renderIconSet = (icons: Icon[]) => `${HEADER}
import type { IconPaths } from './types.js';

export type IconName =
${icons.map(({ name }) => `\t| '${name}'`).join('\n')};

const iconSet: Record<IconName, IconPaths> = {
${icons.map(({ name, outline, solid }) => `\t'${name}': { outline: ${JSON.stringify(outline)}, solid: ${JSON.stringify(solid)} }`).join(',\n')}
};

export default iconSet;
`;

export const renderIndex = (icons: Icon[]) => `${HEADER}
export type { IconName } from './icon-set.js';
export type { IconPaths, IconProps } from './types.js';

export { default as Icon } from './Icon.svelte';
${icons.map(({ name }) => `export { default as ${componentName(name)} } from './icons/${componentName(name)}.svelte';`).join('\n')}
`;
